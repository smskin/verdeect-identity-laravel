<?php

declare(strict_types=1);

namespace Verdeect\IdentityIntegration\Rights;

use Verdeect\IdentityIntegration\Session\IdentitySession;
use Verdeect\IdentityIntegration\Tokens\AccessTokenClaims;
use Verdeect\IdentityIntegration\Tokens\TokenManager;

/**
 * Права вошедшего: роль и ограничения учётной записи.
 *
 * Единственная точка, которой продукт спрашивает «кто это и что ему можно».
 * Разбор токена остаётся внутри библиотеки: продукт не собирает цепочку
 * `sid` → токен → утверждения сам, иначе правило «права берутся из токена
 * на каждом запросе» воспроизводилось бы в каждом продукте, а с ним и ошибки
 * в нём (справка 9.3).
 *
 * **Ничего не запоминает.** Ни в сессии, ни в свойстве: понижение роли доезжает
 * истечением токена доступа (срок задаёт установка, стартовое значение —
 * 5 минут) либо сообщением `user.rights.changed`, и запомненный ответ пережил бы
 * оба. Обращение дешёвое: токен уже обновлён посредником `RefreshIdentityToken`
 * в начале запроса, и `TokenManager` отдаёт его из хранилища без обмена.
 *
 * **Смысла ролей здесь нет и не появится** (справка 9.3): класс отвечает,
 * какая роль у человека, а какие возможности за ней стоят — определяет продукт.
 *
 * Гость получает пустые перечни, а не отказ: вопрос «какие у него права»
 * осмыслен и до входа, и ответ на него — «никаких». Требование входа —
 * дело `RequireIdentitySession`, а не этого класса.
 *
 * **Почему отдельная способность, а не `Session/`.** Тот слой читает сессию
 * и ничего больше — правило зависимостей объявляет его не зависящим ни от чего
 * внутри пакета. Здесь же собираются сессия и токены, как это делает
 * `Profile\ProfileProvider` для профиля. Права и профиль разведены по той же
 * причине, по какой установка шлёт о них **разные** сообщения
 * (`user.rights.changed` и `user.profile.changed`): меняются они по разным
 * поводам и потребителем обрабатываются по-разному.
 */
final class CurrentIdentity
{
    /**
     * Единственное ограничение, известное на момент выпуска пакета.
     *
     * Объявлено константой ради `isReadOnly()`, а не ради решений о доступе:
     * перечень ограничений принадлежит установке, и повторять его здесь
     * целиком значило бы заводить второй источник истины, отстающий от первого.
     */
    private const READ_ONLY = 'read_only';

    public function __construct(
        private readonly IdentitySession $session,
        private readonly TokenManager $tokens,
    ) {}

    /**
     * Роли учётной записи из текущего токена.
     *
     * Утверждение `roles` у пользовательского токена присутствует всегда;
     * пустой перечень означает гостя, а не учётную запись без роли.
     *
     * @return list<string>
     */
    public function roles(): array
    {
        $claims = $this->claims();

        return $claims instanceof AccessTokenClaims ? $claims->roles : [];
    }

    /**
     * Есть ли у вошедшего указанная роль.
     */
    public function hasRole(string $role): bool
    {
        return in_array($role, $this->roles(), true);
    }

    /**
     * Ограничения учётной записи из текущего токена.
     *
     * Утверждение `entitlements` присутствует всегда; отсутствие ограничений
     * выражается пустым перечнем, а не отсутствием утверждения. Перечень
     * значений задаёт установка и расширяет со временем — см. `allowsWrites()`.
     *
     * @return list<string>
     */
    public function entitlements(): array
    {
        $claims = $this->claims();

        return $claims instanceof AccessTokenClaims ? $claims->entitlements : [];
    }

    /**
     * Разрешена ли вошедшему запись.
     *
     * **Выведено из правила, а не из перечня значений**, и это здесь главное.
     * Набор ограничений расширяем; установка требует, чтобы продукт, встретивший
     * незнакомое значение, запрещал все действия, кроме чтения. Проверка вида
     * `in_array('read_only', …)` этому правилу не отвечает: ограничение,
     * добавленное установкой позже, такой продукт не узнает, условие не
     * сработает, и человек получит полные права. Отказа при этом не будет —
     * прав окажется больше положенного, а такую ошибку не ловят тестами.
     *
     * Поэтому запись разрешена тогда и только тогда, когда ограничений нет
     * вовсе. Новое ограничение установки закрывает запись во всех уже
     * развёрнутых продуктах само, без их обновления.
     *
     * Гостю запись не разрешается: перечень у него пуст, но и токена нет —
     * см. оговорку у `claims()`.
     */
    public function allowsWrites(): bool
    {
        $claims = $this->claims();

        if (! $claims instanceof AccessTokenClaims) {
            return false;
        }

        return $claims->entitlements === [];
    }

    /**
     * Находится ли учётная запись в режиме «только чтение».
     *
     * **Предназначено показу человеку, а не принятию решения.** Отказ,
     * объясняющий причину, отличается от отказа «недостаточно прав», и ради
     * этого различия метод и заведён (справка 4.7.4). Решать, можно ли писать,
     * следует `allowsWrites()`: он верен и для ограничений, о которых продукт
     * ещё не знает.
     */
    public function isReadOnly(): bool
    {
        return in_array(self::READ_ONLY, $this->entitlements(), true);
    }

    /**
     * Утверждения текущего токена доступа.
     *
     * `null` — вошедшего нет. Отказа хранилища здесь не перехватывается
     * намеренно: истёкшую сессию обрабатывает `RefreshIdentityToken` в начале
     * запроса — он уничтожает её и уводит на вход, — а перехват здесь скрыл бы
     * ту же беду в консольной команде и в обработчике очереди, где посредника
     * нет.
     */
    private function claims(): AccessTokenClaims|null
    {
        $sid = $this->session->sid();

        if ($sid === null) {
            return null;
        }

        return AccessTokenClaims::parse($this->tokens->accessTokenFor($sid));
    }
}
